// Run with Node 24. Sharp is already provided by Next; no native dependency is required.
import sharp from 'sharp';
import { writeFile } from 'node:fs/promises';
import { tileSymbols } from '../packages/core/src/tileSymbols.ts';
const images={};
for(const symbol of tileSymbols) {
  const svg=`<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="#17211f" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${symbol.paths.map(d=>`<path d="${d}"/>`).join('')}</svg>`;
  const png=await sharp(Buffer.from(svg),{density:288}).resize(96,96).png().toBuffer();
  images[symbol.key]={uri:`data:image/png;base64,${png.toString('base64')}`};
}
await writeFile(new URL('../apps/mobile/src/tileSymbolImages.ts',import.meta.url),`// Generated by scripts/generate-tile-symbol-images.mjs from the shared vector paths.\nexport const tileSymbolImages = ${JSON.stringify(images,null,2)} as const;\n`);
