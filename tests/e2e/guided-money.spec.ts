import {expect,test} from '@playwright/test';
import {homeWorkspace,paydayStep} from './home-navigation';
for(const de of [false,true])for(const width of [320,1365])test(`result first and guided cash plan ${de?'de':'en'} ${width}`,async({page},info)=>{
  const t=(a:string,b:string)=>de?a:b;
  await page.setViewportSize({width,height:900});await page.emulateMedia({reducedMotion:'reduce'});
  await page.clock.setFixedTime(new Date('2026-10-24T12:00:00Z'));
  await page.goto(de?'/de/zuhause':'/home');
  await page.getByRole('button',{name:t('Zuhause erstellen','Create my home'),exact:true}).click();
  await page.evaluate(()=>{
    const p=JSON.parse(localStorage.getItem('eavesence-home-profile-v1')!);
    Object.assign(p,{incomeAmount:2400,incomeFrequency:'monthly',incomeDeferred:false,overviewReviewed:true,backupReminderDismissed:true,incomeExtras:[{id:'extra',kind:'salary14',month:11,amount:2000}]});
    localStorage.setItem('eavesence-home-profile-v1',JSON.stringify(p));
    localStorage.setItem('eavesence-home-costs-v1',JSON.stringify([{id:'rent',name:'Rent',amount:900,category:'housing',frequency:'monthly',nextDueDate:'',updatedAt:'2026-10-24T12:00:00Z'}]));
  });await page.reload();
  const result=page.locator('[data-home-remaining]');
  await expect(result).toBeVisible();await expect(result).toContainText(t('1.500,00','1,500.00'));
  await expect(page.locator('[data-home-monthly-budget]')).not.toHaveAttribute('open');
  await expect(page.locator('.home-month-workspace [data-home-section-navigation]')).toHaveCount(0);
  const month=page.getByRole('group',{name:t('Monat wählen','Choose month'),exact:true});
  await month.getByRole('button',{name:t('Nächster Monat','Next month'),exact:true}).click();
  await expect(result).toContainText(t('3.500,00','3,500.00'));
  await expect(page.locator('[data-checklist-month]')).toContainText('November 2026');
  await page.screenshot({fullPage:true,path:info.outputPath(`guided-home-${de?'de':'en'}-${width}.png`)});
  await homeWorkspace(page,'plan');
  const plan=page.locator('[data-payday-state]');
  await expect(plan).toBeVisible();await expect(plan).toHaveAttribute('data-payday-step','0');
  await expect(plan.locator('form input:visible')).toHaveCount(1);
  await plan.screenshot({path:info.outputPath(`guided-balance-${de?'de':'en'}-${width}.png`)});
  const balance=plan.getByLabel(t('Aktueller Kontostand','Current account balance'),{exact:true});
  await plan.getByRole('button',{name:t('Weiter','Continue'),exact:true}).click();
  await expect(plan).toHaveAttribute('data-payday-step','0');await expect(balance).toBeFocused();
  await balance.fill('1200');await balance.press('Enter');
  await expect(plan).toHaveAttribute('data-payday-step','1');
  await plan.getByRole('button',{name:t('In 14 Tagen','In 14 days'),exact:true}).click();
  await expect(plan.getByRole('button',{name:t('Weiter','Continue'),exact:true})).toBeDisabled();
  await plan.getByLabel(`Rent · ${t('Zahlungstermin','Payment date')}`,{exact:true}).fill('2026-10-30');
  await plan.getByRole('button',{name:t('Termin speichern','Save date'),exact:true}).click();
  await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('eavesence-home-costs-v1')!)[0].nextDueDate)).toBe('2026-10-30');
  await expect(page.locator('[data-home-plan-content]')).toBeVisible();
  await plan.screenshot({path:info.outputPath(`guided-dates-${de?'de':'en'}-${width}.png`)});
  await paydayStep(page,2);
  const everyday=plan.getByLabel(t('Alltagsausgaben bis zum Gehalt','Everyday spending until payday'),{exact:true});
  await everyday.fill('200');
  await plan.screenshot({path:info.outputPath(`guided-everyday-${de?'de':'en'}-${width}.png`)});
  await plan.getByRole('button',{name:t('Zurück','Back'),exact:true}).click();await paydayStep(page,2);await expect(everyday).toHaveValue('200');
  await everyday.press('Enter');
  await expect(plan).toHaveAttribute('data-payday-state','ready');await expect(plan.locator('[data-payday-result]')).toContainText(t('100,00','100.00'));
  await page.screenshot({fullPage:true,path:info.outputPath(`guided-pro-${de?'de':'en'}-${width}.png`)});
  await page.reload();await homeWorkspace(page,'plan');await expect(plan.locator('[data-payday-result]')).toContainText(t('100,00','100.00'));
  await plan.locator('[data-payday-edit-action]').click();
  await expect(plan.locator('form input:visible')).toHaveCount(1);
  await expect(plan.getByRole('button',{name:t('Weiter','Continue'),exact:true})).toHaveCount(0);
  await balance.fill('1100');await balance.press('Enter');
  await expect(plan).toHaveAttribute('data-payday-state','ready');
  await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('eavesence-home-profile-v1')!).planning.cash.balance)).toBe(1100);
  await expect(plan.locator('[data-payday-result]')).toContainText(t('0,00','0.00'));
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
